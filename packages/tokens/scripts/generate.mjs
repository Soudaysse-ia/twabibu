// Generates theme.css (Tailwind 4 @theme + CSS variables) and src/generated/tokens.ts
// from the single source of truth: docs/02-design/design-tokens.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../../docs/02-design/design-tokens.json');
const tokens = JSON.parse(readFileSync(source, 'utf8'));

const flat = (obj, prefix = []) =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' && 'value' in v ? [[[...prefix, k].join('-'), v.value]] : flat(v, [...prefix, k]),
  );

const lines = [];
for (const [name, value] of flat(tokens.color)) lines.push(`  --color-${name}: ${value};`);
lines.push(`  --font-heading: ${tokens.font.family.heading.value};`);
lines.push(`  --font-body: ${tokens.font.family.body.value};`);
for (const [name, value] of flat(tokens.radius)) lines.push(`  --radius-${name}: ${value};`);
for (const [name, value] of flat(tokens.shadow)) lines.push(`  --shadow-${name}: ${value};`);
for (const [name, value] of flat(tokens.size)) lines.push(`  --size-${name}: ${value};`);
lines.push(`  --ease-standard: ${tokens.motion.easing.value};`);

const css = `/* GENERATED by packages/tokens/scripts/generate.mjs from docs/02-design/design-tokens.json (v${tokens.meta.version}). Do not edit. */
@theme static {
${lines.join('\n')}
}
`;
writeFileSync(resolve(here, '../theme.css'), css);

const ts = `// GENERATED from docs/02-design/design-tokens.json (v${tokens.meta.version}). Do not edit.
export const tokens = ${JSON.stringify(
  {
    version: tokens.meta.version,
    color: Object.fromEntries(flat(tokens.color)),
    font: { heading: tokens.font.family.heading.value, body: tokens.font.family.body.value },
    fontSize: Object.fromEntries(flat(tokens.font.size)),
    radius: Object.fromEntries(flat(tokens.radius)),
    shadow: Object.fromEntries(flat(tokens.shadow)),
    size: Object.fromEntries(flat(tokens.size)),
    space: Object.fromEntries(flat(tokens.space)),
    breakpoint: Object.fromEntries(flat(tokens.breakpoint)),
    motion: Object.fromEntries(flat(tokens.motion)),
  },
  null,
  2,
)} as const;
export type Tokens = typeof tokens;
export type ColorToken = keyof Tokens['color'];
`;
mkdirSync(resolve(here, '../src/generated'), { recursive: true });
writeFileSync(resolve(here, '../src/generated/tokens.ts'), ts);
console.log(`tokens v${tokens.meta.version}: ${lines.length} CSS variables`);
